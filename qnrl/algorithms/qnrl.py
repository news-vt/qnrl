@nnx.jit
def epsilon_schedule_linear(eps_start: float, eps_end: float, duration: int, t: int):
    """Linear epsilon decay schedule."""
    slope = (eps_end - eps_start) / duration
    return jnp.max(jnp.array([slope * t + eps_start, eps_end]))


def epsilon_greedy_policy(
    env: gym.Env,
    model_policy: QuantumNativeQNetwork,
    observation: jax.Array,
    t: int, # Current time step.
    duration: int, # Total number of time steps for epsilon decay.
    eps_start: float,
    eps_end: float,
    key: jax.Array,
    ) -> Any:
    """Epsilon-greedy action selection.
    
    Greedy means that the action is selected from the highest probability within the action probability mass function (PMF) generated by the policy model.
    """
    # Decay epsilon based on current time step.
    eps = epsilon_schedule_linear(eps_start=eps_start, eps_end=eps_end, duration=duration, t=t)
    # Action selection.
    key, subkey = jax.random.split(key)
    # Explore via random uniform action selection.
    if jax.random.uniform(key=subkey) < eps:
        action = env.action_space.sample()
        action_pmf = jnp.array([1./env.action_space.n] * env.action_space.n) # Uniform distribution.
        return action, action_pmf
    else:
        # Generate action distribution from input observation.
        action_pmf = model_policy.call_gen_action_dist(observation).squeeze() # (n_actions,)
        # Take greedy action.
        action = jnp.argmax(action_pmf, axis=-1).item() # ()
        return action, action_pmf


def epsilon_stochastic_policy(
    env: gym.Env,
    model_policy: QuantumNativeQNetwork,
    observation: jax.Array,
    t: int, # Current time step.
    duration: int, # Total number of time steps for epsilon decay.
    eps_start: float,
    eps_end: float,
    key: jax.Array,
    ) -> Any:
    """Epsilon-stochastic action selection.
    
    Stochastic means that the action is selected at random based on the action probability mass function (PMF) generated by the policy model.
    """
    # Decay epsilon based on current time step.
    eps = epsilon_schedule_linear(eps_start=eps_start, eps_end=eps_end, duration=duration, t=t)
    # Action selection.
    key, subkey = jax.random.split(key)
    # Explore via random uniform action selection.
    if jax.random.uniform(key=subkey) < eps:
        action = env.action_space.sample()
        action_pmf = jnp.array([1./env.action_space.n] * env.action_space.n) # Uniform distribution.
        return action, action_pmf
    else:
        # Generate action distribution from input observation.
        action_pmf = model_policy.call_gen_action_dist(observation).squeeze() # (n_actions,)
        # Randomly choose an action according to the action PMF.
        key, subkey = jax.random.split(key)
        action = jax.random.choice(key=subkey, a=model_policy.n_actions, p=action_pmf).item()
        return action, action_pmf


def epsilon_phased_stochastic_greedy_policy(
    env: gym.Env,
    model_policy: QuantumNativeQNetwork,
    observation: jax.Array,
    t: int, # Current time step.
    duration: int, # Total number of time steps for epsilon decay.
    eps_start: float,
    eps_end: float,
    key: jax.Array,
    ) -> Any:
    """Epsilon-phased-stochastic-greedy action selection.
    
    Two levels of epsilon randomization are used.
    1. First decayed epsilon sample dictates random uniform selection for exploration.
    2. Second decayed epsilon sample dictates action selection should be based on policy PMF.
        - If epsilon, then sample action according to policy PMF.
        - Otherwise, take greedy action selection based on policy PMF.
    """
    # Decay epsilon based on current time step.
    eps = epsilon_schedule_linear(eps_start=eps_start, eps_end=eps_end, duration=duration, t=t)
    # Action selection.
    key, subkey = jax.random.split(key)
    # Explore via random uniform action selection.
    if jax.random.uniform(key=subkey) < eps:
        action = env.action_space.sample()
        action_pmf = jnp.array([1./env.action_space.n] * env.action_space.n) # Uniform distribution.
        return action, action_pmf
    # Policy should be used for sampling.
    else:
        # Generate action distribution from input observation.
        action_pmf = model_policy.call_gen_action_dist(observation).squeeze() # (n_actions,)
        
        # Check again to see if action should be selected stochastically from model, or greedy.
        key, subkey = jax.random.split(key)
        # Stochastic.
        if jax.random.uniform(key=subkey) < eps:
            key, subkey = jax.random.split(key)
            action = jax.random.choice(key=subkey, a=model_policy.n_actions, p=action_pmf).item()
            return action, action_pmf
        # Greedy.
        else:
            action = jnp.argmax(action_pmf, axis=-1).item() # ()
            return action, action_pmf



